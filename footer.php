  <script>
    document.addEventListener('DOMContentLoaded', function () {
      var menuBtn = document.getElementById('mobile-menu-btn');
      var menuClose = document.getElementById('mobile-menu-close');
      var menu = document.getElementById('mobile-menu');
      var header = document.getElementById('site-header');

      function openMenu() {
        if (!menu) return;
        menu.classList.add('is-open');
        document.body.classList.add('menu-open');
        if (menuBtn) menuBtn.setAttribute('aria-expanded', 'true');
      }

      function closeMenu() {
        if (!menu) return;
        menu.classList.remove('is-open');
        document.body.classList.remove('menu-open');
        if (menuBtn) menuBtn.setAttribute('aria-expanded', 'false');
      }

      function toggleMenu(e) {
        if (e) {
          e.preventDefault();
          e.stopPropagation();
        }
        if (menu && menu.classList.contains('is-open')) closeMenu();
        else openMenu();
      }

      if (menuBtn) menuBtn.addEventListener('click', toggleMenu);
      if (menuClose) menuClose.addEventListener('click', function (e) {
        e.preventDefault();
        e.stopPropagation();
        closeMenu();
      });
      if (menu) {
        menu.querySelectorAll('a').forEach(function (link) {
          link.addEventListener('click', closeMenu);
        });
      }
      document.addEventListener('keydown', function (e) {
        if (e.key === 'Escape') closeMenu();
      });

      /* Header shadow on scroll */
      if (header) {
        var onScroll = function () {
          if (window.scrollY > 12) header.classList.add('is-scrolled');
          else header.classList.remove('is-scrolled');
        };
        window.addEventListener('scroll', onScroll, { passive: true });
        onScroll();
      }

      /* Swiper */
      if (typeof Swiper !== 'undefined' && document.querySelector('.swiper.is-services')) {
        new Swiper('.swiper.is-services', {
          slidesPerView: 'auto',
          spaceBetween: '8%',
          breakpoints: { 768: { spaceBetween: '2%' } },
          scrollbar: {
            el: '.swiper-drag-wrapper.is-services',
            draggable: true,
            dragClass: 'swiper-drag-services',
            snapOnRelease: true,
          },
          navigation: {
            nextEl: '.service-next',
            prevEl: '.service-prev',
            disabledClass: 'is-disabled',
          },
        });
      }

      /* Hero GSAP */
      if (typeof gsap !== 'undefined') {
        if (typeof ScrollTrigger !== 'undefined') gsap.registerPlugin(ScrollTrigger);
        var heroWords = document.querySelectorAll('.hero-word');
        var heroStats = document.querySelectorAll('.hero-stat');
        var goldLine = document.getElementById('hero-gold-line');
        var scrollInd = document.querySelector('.hero-scroll-indicator');
        if (heroWords.length) {
          gsap.to(heroWords, { opacity: 1, y: 0, duration: 0.85, stagger: 0.16, ease: 'power3.out', delay: 0.25 });
        }
        if (goldLine) setTimeout(function () { goldLine.classList.add('is-visible'); }, 180);
        if (heroStats.length) {
          gsap.to(heroStats, { opacity: 1, y: 0, duration: 0.75, stagger: 0.1, ease: 'power3.out', delay: 0.9 });
        }
        if (scrollInd) {
          gsap.to(scrollInd, {
            opacity: 1, duration: 0.5, delay: 1.6,
            onComplete: function () { scrollInd.classList.add('is-visible'); }
          });
        }
      }

      /* Energy form fields */
      var interestSelect = document.getElementById('interest');
      var energyFields = document.getElementById('energy-fields');
      if (interestSelect && energyFields) {
        function toggleEnergy() {
          var show = interestSelect.value === 'Energy & Petroleum';
          energyFields.classList.toggle('hidden', !show);
          energyFields.querySelectorAll('[data-energy-required]').forEach(function (el) {
            if (show) el.setAttribute('required', 'required');
            else el.removeAttribute('required');
          });
        }
        interestSelect.addEventListener('change', toggleEnergy);
        toggleEnergy();
      }

      var enquiryForm = document.getElementById('enquiry-form');
      if (enquiryForm) {
        enquiryForm.addEventListener('submit', function (e) {
          var hp = enquiryForm.querySelector('input[name="website_url"]');
          if (hp && hp.value.trim() !== '') {
            e.preventDefault();
            return false;
          }
        });
      }
    });
